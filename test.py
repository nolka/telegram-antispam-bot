    # Инициализация препроцессора для русского языка
    preprocessor = RussianTextPreprocessor(
        use_stemming=True, use_lemmatization=True
    )

    # Применение препроцессинга
    print("Обработка сообщений...")
    processed_messages = []
    for i, message in enumerate(raw_messages):
        if i % 1000 == 0:
            print(f"Обработано {i}/{len(raw_messages)} сообщений")
        processed_messages.append(preprocessor.preprocess_text(message))

    # Разделение данных на обучающую и тестовую выборки
    X_train, X_test, y_train, y_test = train_test_split(
        processed_messages,
        labels,
        test_size=0.2,
        random_state=42,
        stratify=labels,
    )

    print(f"Размер обучающей выборки: {len(X_train)}")
    print(f"Размер тестовой выборки: {len(X_test)}")

    # Создание TF-IDF векторайзера для русского языка
    vectorizer = TfidfVectorizer(
        max_features=10000,
        lowercase=True,
        ngram_range=(1, 3),
        min_df=2,
        max_df=0.95,
        sublinear_tf=True,
    )

    # Преобразование текстов в числовые признаки
    print("Векторизация текстов...")
    X_train_tfidf = vectorizer.fit_transform(X_train)
    X_test_tfidf = vectorizer.transform(X_test)

    # Обучение модели
    model = MultinomialNB(alpha=0.01)
    model.fit(X_train_tfidf, y_train)

    # Предсказание и оценка
    y_pred = model.predict(X_test_tfidf)

    print(f"\n{'=' * 50}")
    print("ПРОИЗВОДИТЕЛЬНОСТЬ МОДЕЛИ")
    print(f"{'=' * 50}")
    print(f"Точность: {accuracy_score(y_test, y_pred):.4f}")
    print("\nОтчет классификации:")
    print(classification_report(y_test, y_pred))
    print("\nМатрица ошибок:")
    print(confusion_matrix(y_test, y_pred))

    # Функция для предсказания спама на русском
    def predict_russian_spam(message, threshold=0.5):
        processed_msg = preprocessor.preprocess_text(message)
        message_vec = vectorizer.transform([processed_msg])
        probability = model.predict_proba(message_vec)[0][1]
        prediction = 1 if probability > threshold else 0

        return {
            "prediction": "СПАМ" if prediction == 1 else "НЕ СПАМ",
            "spam_probability": probability,
            "processed_message": processed_msg,
        }

